export type SocialIconName =
  | 'linkedin'
  | 'instagram'
  | 'facebook'
  | 'x'
  | 'twitter'
  | 'youtube'
  | 'whatsapp'
  | 'email'
  | 'website'

type IconNode = {
  tag: 'path' | 'rect'
  attrs: Record<string, string | number>
}

export interface SocialIconDef {
  viewBox: string
  renderMode: 'fill' | 'stroke'
  nodes: IconNode[]
}

const normalize = (value?: string | null) =>
  String(value || '')
    .trim()
    .toLowerCase()

export const resolveSocialIconName = (name?: string | null, url?: string | null): SocialIconName => {
  const normalizedName = normalize(name)
  const normalizedUrl = normalize(url)
  const source = `${normalizedName} ${normalizedUrl}`

  if (source.includes('mailto:') || source.includes('email')) return 'email'
  if (source.includes('linkedin') || source.includes('linkedin.com')) return 'linkedin'
  if (source.includes('instagram') || source.includes('instagram.com')) return 'instagram'
  if (source.includes('facebook') || source.includes('facebook.com') || source.includes('fb.com')) return 'facebook'
  if (source.includes('youtube') || source.includes('youtube.com') || source.includes('youtu.be')) return 'youtube'
  if (source.includes('whatsapp') || source.includes('wa.me') || source.includes('whatsapp.com')) return 'whatsapp'
  if (source.includes('twitter') || source.includes('twitter.com') || source.includes('x.com') || normalizedName === 'x') return 'x'
  if (/^https?:\/\//.test(normalizedUrl) || normalizedName.includes('website')) return 'website'

  return 'website'
}

